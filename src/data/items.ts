const ITEM_BY_ID = new Map(ALL_CATALOG_ITEMS.map((item) => [item.id, item]));
const PIN_BY_ID = new Map(MAP_PINS.map((pin) => [pin.id, pin]));

export function getItemById(id: string): CatalogItem | undefined {
  return ITEM_BY_ID.get(id);
}

export function findCatalogItemByName(name: string): CatalogItem | undefined {
  const target = name.replace(/\s*\(.*?\)/g, '').trim().toLowerCase();
  return (
    ALL_CATALOG_ITEMS.find((it) => it.name.toLowerCase() === target) ||
    ALL_CATALOG_ITEMS.find((it) => it.name.toLowerCase().includes(target) || target.includes(it.name.toLowerCase()))
  );
}

export function resolveMapPinsForItem(item: CatalogItem): string[] {
  if (item.mapPinIds?.length) {
    return item.mapPinIds.filter((id) => PIN_BY_ID.has(id));
  }
  const needle = item.name.replace(/\s*\(.*?\)/g, '').trim().toLowerCase();
  const matched = MAP_PINS.filter((pin) => {
    const haystack = [
      ...(pin.fishHere ?? []),
      ...(pin.forageHere ?? []),
      ...(pin.shopsItems ?? []),
      ...(pin.resourcesHere ?? []),
      ...(pin.tags ?? []),
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(needle);
  }).map((p) => p.id);

  return matched.length ? matched : item.category === 'Fish' ? ['the-beach', 'mountain-lake'] : ['farm'];
}
