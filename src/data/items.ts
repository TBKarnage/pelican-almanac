// Dynamically match bundles and villager gift lovers/likers for zero-staleness cross-linking
function buildLovedLikedMaps() {
  const loveMap = new Map<string, string[]>();
  const likeMap = new Map<string, string[]>();

  for (const v of VILLAGERS) {
    for (const raw of v.loves) {
      const clean = raw.replace(/\s*\(.*?\)/g, '').trim().toLowerCase();
      loveMap.set(clean, [...(loveMap.get(clean) ?? []), v.name]);
    }
    for (const raw of v.likes) {
      const clean = raw.replace(/\s*\(.*?\)/g, '').trim().toLowerCase();
      likeMap.set(clean, [...(likeMap.get(clean) ?? []), v.name]);
    }
  }
  return { loveMap, likeMap };
}

function buildBundleMap() {
  const map = new Map<string, string[]>();
  for (const b of BUNDLES) {
    for (const req of b.items) {
      if (req.itemId) {
        const list = map.get(req.itemId) ?? [];
        if (!list.includes(b.name)) list.push(b.name);
        map.set(req.itemId, list);
      }
      const lowerName = req.name.replace(/\s*\(.*?\)/g, '').trim().toLowerCase();
      const listByName = map.get(lowerName) ?? [];
      if (!listByName.includes(b.name)) listByName.push(b.name);
      map.set(lowerName, listByName);
    }
  }
  return map;
}

const { loveMap, likeMap } = buildLovedLikedMaps();
const bundleMap = buildBundleMap();

function enrichWithSocialAndBundles(item: CatalogItem): CatalogItem {
  const keyName = item.name.replace(/\s*\(.*?\)/g, '').trim().toLowerCase();
  const lovedBy = Array.from(new Set([...(item.lovedBy ?? []), ...(loveMap.get(keyName) ?? [])]));
  const likedBy = Array.from(new Set([...(item.likedBy ?? []), ...(likeMap.get(keyName) ?? [])]));
  const bundleIds = Array.from(
    new Set([
      ...(item.bundleIds ?? []),
      ...(bundleMap.get(item.id) ?? []),
      ...(bundleMap.get(keyName) ?? []),
    ])
  );
  return {
    ...item,
    lovedBy: lovedBy.length ? lovedBy : undefined,
    likedBy: likedBy.length ? likedBy : undefined,
    bundleIds: bundleIds.length ? bundleIds : undefined,
  };
}

